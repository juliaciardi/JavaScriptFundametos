const opcao = 3;

switch (opcao) {
    case 1:
        console.log("Cadastrar cliente");
        break;
    case 2:
        console.log("Listar cliente");
        break;
    case 3:
        console.log("Editar cliente");
        break;
    case 4:
        console.log("Excluir cliente");
        break;
    case 0:
        console.log("Sair do sistema");
        break;
    default:
        console.log("Opção invalida");
}